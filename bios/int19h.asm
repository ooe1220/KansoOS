[BITS 16]

; ============================================================
; INT 19h ハンドラ（ブートストラップ）
; ・LBA 0 の MBR を 0x0000:0x7C00 に読み込む
; ・0xAA55 確認
; ・成功すれば 0x0000:0x7C00 へ飛ぶ
; ============================================================

; DAP（Disk Address Packet）をコード直後に配置
int19_dap:
    db 0x10          ; サイズ
    db 0x00          ; 予約
    dw 1             ; 読み込むセクタ数
    dw 0x0000        ; バッファオフセット
    dw 0x07C0        ; バッファセグメント
    dd 0             ; LBA 0（MBR）
    dd 0             ; LBA 上位32bit（今回は不使用）

int19h_handler:

    ; ----------------------------
    ; INT 13h 拡張読み込み (AH=0x42)
    ; ----------------------------
    mov ah, 0x42
    mov ax, 0xF000
    mov ds, ax
    mov si, int19_dap   ; DS:SI = DAP
    int 0x13
    jc int19_err        ; CF=1 ならエラー

    ; ----------------------------
    ; 0xAA55 確認
    ; ----------------------------
    xor ax, ax
    mov ds, ax
    mov bx, 0x7C00
    cmp word [bx + 510], 0xAA55
    jne int19_err

    ; ----------------------------
    ; MBR へジャンプ
    ; ----------------------------
    
    jmp 0x0000:0x7C00

; ----------------------------
; エラー時停止
; ----------------------------
int19_err:
    cli
    hlt
    jmp int19_err
